#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

MOJO_BIN=""

# Resolve Mojo 1.2 toolchain in current shell (never inside $(...) so exports persist)
resolve_mojo() {
    if [[ -n "${MOJO:-}" && -x "${MOJO}" ]]; then
        MOJO_BIN="${MOJO}"
        return
    fi
    local candidate_prefix
    for candidate_prefix in \
        "${ROOT}/.pixi/envs/default" \
        "${ROOT}/../.pixi/envs/default" \
        "${ROOT}/../rollercoaster/.pixi/envs/default" \
        "${HOME}/.pixi/envs/turbomojo"; do
        if [[ -x "${candidate_prefix}/bin/mojo" ]]; then
            export MOJO_PREFIX="${candidate_prefix}"
            export MODULAR_HOME="${candidate_prefix}/share/max"
            export LD_LIBRARY_PATH="${candidate_prefix}/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
            MOJO_BIN="${candidate_prefix}/bin/mojo"
            return
        fi
    done
    if command -v mojo >/dev/null 2>&1; then
        MOJO_BIN="$(command -v mojo)"
        return
    fi
    echo "[Flint] ERROR: Mojo 1.2 compiler not found. Run 'pixi install' or set MOJO=/path/to/mojo." >&2
    exit 1
}

compile_mojo() {
    local src="$1"
    local out="$2"
    local opt="${3:--O3}"
    local tmp
    tmp="$(mktemp "/tmp/flint-link-$(basename "$out")-XXXXXX")"
    rm -f "$tmp" "$out"
    local nd_src="${NEONDRIFT_ROOT:-/home/user/neondrift}/src"
    local rct_src="${ROLLERCOASTER_ROOT:-/home/user/rollercoaster}/src"
    local extra_inc=""
    if [[ -d "$nd_src" ]]; then extra_inc="$extra_inc -I $nd_src"; fi
    if [[ -d "$rct_src" ]]; then extra_inc="$extra_inc -I $rct_src"; fi
    if ! "$MOJO_BIN" build "$src" -o "$tmp" -I "${ROOT}/src" -I "${ROOT}/tests" $extra_inc "$opt" --fp-mode contract=off; then
        rm -f "$tmp"
        return 1  # also when called from an `if`, where `set -e` does not stop us
    fi
    rm -f "$out"
    cp "$tmp" "$out"
    chmod +x "$out"
    rm -f "$tmp"
}

write_build_stamp() {
    local mojo_bin="$1"
    local commit="dev"
    local dirty="False"
    if git rev-parse --short HEAD >/dev/null 2>&1; then
        commit="$(git rev-parse --short HEAD)"
        if [[ -n "$(git status --porcelain 2>/dev/null || true)" ]]; then
            dirty="True"
        fi
    fi
    local mojo_ver
    mojo_ver="$("$mojo_bin" --version 2>/dev/null | awk '{print $2}' || echo "1.2.0")"
    cat > "${ROOT}/src/flint/core/build_stamp.mojo" <<EOF
"""Generated by tools/flint.sh — build provenance stamp."""
comptime BUILD_COMMIT: String = "${commit}"
comptime BUILD_DIRTY: Bool = ${dirty}
comptime BUILD_MOJO: String = "${mojo_ver}"
EOF
}

cmd_sync() {
    bash "${ROOT}/tools/sync_from_deepsong.sh" "$@"
}

cmd_build() {
    resolve_mojo
    write_build_stamp "$MOJO_BIN"
    mkdir -p "${ROOT}/build"

    local target="${1:-all}"
    if [[ "$target" == "all" || "$target" == "spark" ]]; then
        echo "[Flint] Building examples/minimal_spark/main.mojo -> build/flint-spark ..."
        compile_mojo "${ROOT}/examples/minimal_spark/main.mojo" "${ROOT}/build/flint-spark"
    fi
    if [[ "$target" == "all" || "$target" == "world" ]]; then
        echo "[Flint] Building examples/open_world/main.mojo -> build/flint-world ..."
        compile_mojo "${ROOT}/examples/open_world/main.mojo" "${ROOT}/build/flint-world"
    fi
    if [[ "$target" == "all" || "$target" == "cycles" ]]; then
        echo "[Flint] Building examples/cycles/main.mojo -> build/flint-cycles ..."
        compile_mojo "${ROOT}/examples/cycles/main.mojo" "${ROOT}/build/flint-cycles"
        echo "[Flint] Building tests/test_cycles.mojo -> build/flint-cycles-test ..."
        compile_mojo "${ROOT}/tests/test_cycles.mojo" "${ROOT}/build/flint-cycles-test"
    fi
    if [[ "$target" == "all" || "$target" == "kms" ]]; then
        echo "[Flint] Building examples/kms_console/main.mojo -> build/flint-kms ..."
        compile_mojo "${ROOT}/examples/kms_console/main.mojo" "${ROOT}/build/flint-kms"
    fi
    if [[ "$target" == "all" || "$target" == "kms3d" ]]; then
        echo "[Flint] Building examples/kms_3d/main.mojo -> build/flint-kms3d ..."
        compile_mojo "${ROOT}/examples/kms_3d/main.mojo" "${ROOT}/build/flint-kms3d"
    fi
    if [[ "$target" == "all" || "$target" == "pack" ]]; then
        echo "[Flint] Building examples/pack_cli/main.mojo -> build/flint-pack ..."
        compile_mojo "${ROOT}/examples/pack_cli/main.mojo" "${ROOT}/build/flint-pack"
    fi
    if [[ "$target" == "all" || "$target" == "test" ]]; then
        echo "[Flint] Building tests/test_flint.mojo -> build/flint-test ..."
        compile_mojo "${ROOT}/tests/test_flint.mojo" "${ROOT}/build/flint-test"
    fi
    if [[ "$target" == "all" || "$target" == "test" || "$target" == "e2e" ]]; then
        echo "[Flint] Building tests/test_e2e.mojo -> build/flint-e2e ..."
        compile_mojo "${ROOT}/tests/test_e2e.mojo" "${ROOT}/build/flint-e2e"
    fi
    echo "[Flint] Build complete."
}

cmd_pack() {
    cmd_build pack
    "${ROOT}/build/flint-pack" "$@"
}

cmd_test() {
    local sub="${1:-}"
    if [[ "$sub" == "e2e" ]]; then
        cmd_build e2e
        echo "[Flint] Running Flint Engine E2E test suite..."
        "${ROOT}/build/flint-e2e"
    elif [[ "$sub" == "unit" ]]; then
        cmd_build test
        echo "[Flint] Running Flint Engine unit test suite..."
        "${ROOT}/build/flint-test"
    else
        cmd_build test
        echo "[Flint] Running Flint Engine test suite..."
        "${ROOT}/build/flint-test"
        echo "[Flint] Running Flint Engine E2E test suite..."
        "${ROOT}/build/flint-e2e"
    fi
}

cmd_cycles() {
    cmd_build cycles
    exec "${ROOT}/build/flint-cycles" "$@"
}

cmd_play() {
    cmd_build spark
    exec "${ROOT}/build/flint-spark" "$@"
}

cmd_kms() {
    cmd_build kms
    FLINT_BACKEND="${FLINT_BACKEND:-kms}" exec "${ROOT}/build/flint-kms" "$@"
}

cmd_kms3d() {
    cmd_build kms3d
    FLINT_BACKEND="${FLINT_BACKEND:-kms}" exec "${ROOT}/build/flint-kms3d" "$@"
}

# Live preview: keep a program's window open while you edit. Every save of a .mojo file
# (the program's own tree and Flint's src/) rebuilds it in the background; a good build
# replaces the window, a failed one prints the errors and leaves the old window running.
preview_source() {
    case "$1" in
        spark|play) echo "${ROOT}/examples/minimal_spark/main.mojo" ;;
        world)      echo "${ROOT}/examples/open_world/main.mojo" ;;
        cycles)     echo "${ROOT}/examples/cycles/main.mojo" ;;
        *)
            if [[ -d "$1" && -f "$1/main.mojo" ]]; then echo "$(cd "$1" && pwd)/main.mojo"
            elif [[ -d "$1" && -f "$1/src/main.mojo" ]]; then echo "$(cd "$1/src" && pwd)/main.mojo"
            elif [[ -f "$1" ]]; then echo "$(cd "$(dirname "$1")" && pwd)/$(basename "$1")"
            fi ;;
    esac
}

cmd_preview() {
    local target="${1:-}"
    if [[ -z "$target" || "$target" == "-h" || "$target" == "--help" ]]; then
        echo "Usage: bash tools/flint.sh preview <spark|world|cycles|program.mojo|project_dir> [--release] [-- program args...]"
        echo "  Rebuilds on every .mojo save and swaps the window. -O1 builds; --release uses -O3."
        echo "  Runs windowed (FLINT_WINDOWED=1); Ctrl+C stops the preview and its window."
        return 1
    fi
    shift
    local opt="-O1"
    local args=()
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --release) opt="-O3"; shift ;;
            --) shift; args=("$@"); break ;;
            *) args+=("$1"); shift ;;
        esac
    done
    local src
    src="$(preview_source "$target")"
    if [[ -z "$src" || ! -f "$src" ]]; then
        echo "[Preview] No program at '$target' (a target name, a .mojo file, or a directory with main.mojo / src/main.mojo)." >&2
        return 1
    fi
    resolve_mojo
    [[ -f "${ROOT}/src/flint/core/build_stamp.mojo" ]] || write_build_stamp "$MOJO_BIN"
    # A program inside a project (.../src/...) runs from the project root, where its assets live.
    local run_dir="$ROOT"
    local watch_dirs=("${ROOT}/src" "$(dirname "$src")")
    if [[ "$src" == */src/* ]]; then
        run_dir="${src%%/src/*}"
        watch_dirs+=("${run_dir}/src")
    fi
    local name
    name="$(basename "$(dirname "$src")")"
    [[ "$name" == "src" ]] && name="$(basename "$run_dir")"
    mkdir -p "${ROOT}/build/preview"
    local bin="${ROOT}/build/preview/${name}"
    local stamp="${ROOT}/build/preview/.${name}.stamp"
    local child=0

    stop_child() {
        if [[ $child -gt 0 ]] && kill -0 "$child" 2>/dev/null; then
            kill -TERM "$child" 2>/dev/null || true
            for _ in $(seq 30); do kill -0 "$child" 2>/dev/null || break; sleep 0.1; done
            kill -KILL "$child" 2>/dev/null || true
            wait "$child" 2>/dev/null || true
        fi
        child=0
    }
    launch_child() {
        ( cd "$run_dir" && FLINT_WINDOWED="${FLINT_WINDOWED:-1}" exec "$bin" "${args[@]+"${args[@]}"}" ) &
        child=$!
        echo "[Preview] Running ${name} (pid ${child}). Edit and save; Ctrl+C stops."
    }
    rebuild() {
        touch "$stamp"  # edits saved while compiling trigger the next rebuild
        local started=$SECONDS
        echo "[Preview] Building ${src#${run_dir}/} (${opt}) ..."
        if compile_mojo "$src" "${bin}.next" "$opt"; then
            echo "[Preview] Built in $((SECONDS - started)) s."
            stop_child
            if mv -f "${bin}.next" "$bin"; then
                launch_child
            fi
        else
            echo "[Preview] Build failed after $((SECONDS - started)) s; the previous window keeps running. Fix and save again."
        fi
    }
    changed_file() {
        find "${watch_dirs[@]}" -name '*.mojo' -newer "$stamp" \
            ! -path '*/build/*' ! -name 'build_stamp.mojo' -print -quit 2>/dev/null
    }

    trap 'echo; echo "[Preview] Stopping."; stop_child; exit 0' INT TERM
    trap 'stop_child' EXIT  # never leave a window behind, however the preview ends
    echo "[Preview] Watching: ${watch_dirs[*]}"
    rebuild
    while true; do
        sleep 0.5
        if [[ $child -gt 0 ]] && ! kill -0 "$child" 2>/dev/null; then
            wait "$child" 2>/dev/null || true
            child=0
            echo "[Preview] The window closed. Save a file to build and open it again (Ctrl+C to quit)."
        fi
        local hit
        hit="$(changed_file)"
        if [[ -n "$hit" ]]; then
            sleep 0.3  # let an editor finish writing (and catch save-all)
            echo "[Preview] Changed: ${hit#${run_dir}/}"
            rebuild
        fi
    done
}

cmd_world() {
    cmd_build world
    mkdir -p "${ROOT}/build/shots"
    exec "${ROOT}/build/flint-world" "$@"
}

cmd_shot() {
    cmd_build spark
    mkdir -p "${ROOT}/build/shots"
    "${ROOT}/build/flint-spark" --shots
}

cmd_gate() {
    echo "============================================================"
    echo " FLINT ENGINE VERIFICATION GATE"
    echo "============================================================"
    cmd_sync --verify
    cmd_build all
    "${ROOT}/build/flint-test"
    "${ROOT}/build/flint-e2e"
    "${ROOT}/build/flint-cycles-test"
    mkdir -p "${ROOT}/build/shots"
    "${ROOT}/build/flint-spark" --shots

    echo "[Flint Gate] Verifying Downstream NeonDrift 2099 Compatibility..."
    (cd "${NEONDRIFT_ROOT:-/home/user/neondrift}" && bash tools/build.sh game && ./build/neondrift --pack)

    echo "[Flint Gate] Verifying Downstream Rollercoaster Compatibility..."
    (cd "${ROLLERCOASTER_ROOT:-/home/user/rollercoaster}" && bash tools/build.sh test)

    echo "============================================================"
    echo " [PASS] FLINT GATE PASSED (Zero-Leak + Tests + Games Verified)"
    echo "============================================================"
}

cmd_new() {
    local dest="${1:-}"
    if [[ -z "$dest" ]]; then
        echo "Usage: tools/flint.sh new <target_directory>" >&2
        exit 1
    fi
    mkdir -p "${dest}/src" "${dest}/tools"
    local app_name
    app_name="$(basename "$dest")"

    cat > "${dest}/pixi.toml" <<EOF
[workspace]
name = "${app_name}"
version = "0.1.0"
description = "Pure-Mojo 1.2 game powered by Flint Engine"
channels = ["https://conda.modular.com/max", "conda-forge"]
platforms = ["linux-64", "linux-aarch64"]

[dependencies]
mojo = ">=1.2.0,<1.3"

[tasks]
play = "bash tools/run.sh"
EOF

    cat > "${dest}/tools/run.sh" <<EOF
#!/usr/bin/env bash
set -euo pipefail
APP_ROOT="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")/.." && pwd)"
FLINT_ROOT="\${FLINT_ROOT:-${ROOT}}"
mkdir -p "\${APP_ROOT}/build"
bash "\${FLINT_ROOT}/tools/flint.sh" build spark >/dev/null 2>&1 || true
MOJO_BIN="\${MOJO:-mojo}"
if [[ -x "\${FLINT_ROOT}/.pixi/envs/default/bin/mojo" ]]; then
    MOJO_BIN="\${FLINT_ROOT}/.pixi/envs/default/bin/mojo"
fi
"\$MOJO_BIN" run -I "\${FLINT_ROOT}/src" -I "\${APP_ROOT}/src" "\${APP_ROOT}/src/main.mojo" "\$@"
EOF
    chmod +x "${dest}/tools/run.sh"

    cat > "${dest}/src/main.mojo" <<EOF
"""Starter game scaffolded by Flint Engine ('flint.sh new')."""
from flint.core.math import Vec3
from flint.platform.wayland import WaylandWindow
from flint.platform.input import InputState
from flint.render.simd_canvas import Camera3D, SimdCanvas


def main():
    var canvas = SimdCanvas(960, 540)
    var cam = Camera3D(960, 540, Vec3(0.0, 3.0, 7.5), Vec3(0.0, 0.0, 0.0), 55.0)
    var win = WaylandWindow()
    var input = InputState()
    if not win.initialize(960, 540):
        print("Headless environment detected — initialized Flint SimdCanvas (960x540) cleanly.")
        return
    while not win.close_requested:
        input.begin_frame()
        win.poll(input)
        if input.key_pressed(256):
            break
        canvas.clear(0x141E30, 0x0A0E17)
        canvas.draw_line_3d(cam, Vec3(-2.0, 0.0, 0.0), Vec3(2.0, 0.0, 0.0), 0xF49E38, 2)
        canvas.draw_text(20, 20, "${app_name^^} - POWERED BY FLINT", 0xF49E38, 2)
        win.present(canvas.pixels, canvas.width, canvas.height)
    win.close()
EOF
    echo "[Flint] Scaffolded new Flint game project at: ${dest}"
}

subcmd="${1:-help}"
shift || true
case "$subcmd" in
    sync)  cmd_sync "$@" ;;
    build) cmd_build "$@" ;;
    pack)  cmd_pack "$@" ;;
    test)  cmd_test "$@" ;;
    play)  cmd_play "$@" ;;
    world) cmd_world "$@" ;;
    kms)   cmd_kms "$@" ;;
    kms3d) cmd_kms3d "$@" ;;
    preview) cmd_preview "$@" ;;
    cycles) cmd_cycles "$@" ;;
    shot)  cmd_shot "$@" ;;
    gate)  cmd_gate "$@" ;;
    new)   cmd_new "$@" ;;
    *)
        echo "Flint Engine CLI (Pure Mojo 1.2)"
        echo "Usage: bash tools/flint.sh <command>"
        echo ""
        echo "Commands:"
        echo "  sync [deepsong_dir]  Harvest latest pure-Mojo libraries from Deepsong & run Zero-Leak Gate"
        echo "  cycles live|render|query ...  Pure-Mojo TidalCycles-style live coding (docs/CYCLES.md)"
        echo "  build [all|spark|world|kms|kms3d|pack|test|cycles] Compile Flint showcase, open-world, pack CLI & test binaries (-O3)"
        echo "  pack <out.flpk> <files...> Bundle loose assets into a single .flpk VFS archive"
        echo "  test                 Build and run Flint Engine verification suite"
        echo "  play                 Launch interactive 'minimal_spark' 2D+3D showcase"
        echo "  kms [--probe]        Run the bare-display DRM/KMS demo from a text console (no X11/Wayland)"
        echo "  kms3d                GPU 3D on the bare display: AAA Vulkan renderer presenting via VK_KHR_display"
        echo "  preview <program>    Live preview: rebuild on save and swap the window (spark|world|cycles|file.mojo|dir)"
        echo "  world [--shots]      Launch 512m x 512m AAA Vulkan Open-World sandbox (or render 3 720p vistas)"
        echo "  shot                 Render deterministic headless PNG to build/shots/flint_spark.png"
        echo "  gate                 Run full verification gate (sync + build + test + headless shot)"
        echo "  new <dir>            Scaffold a standalone Flint game project"
        ;;
esac
