cmd_new() {
    local dest="${1:-}"
    if [[ -z "$dest" ]]; then
        echo "Usage: tools/flint.sh new <target_directory>" >&2
        exit 1
    fi
    mkdir -p "${dest}/src" "${dest}/assets" "${dest}/tools"
    local app_name
    app_name="$(basename "$dest")"

    cat > "${dest}/flint.toml" <<EOF
[project]
name = "${app_name}"
version = "0.1.0"
entry = "src/main.mojo"

[engine]
flint_version = ">=5.0"
deterministic_fp = true
werror = true

[window]
title = "${app_name}"
width = 1280
height = 720
vsync = true

[physics]
fixed_hz = 60

[net]
tick_hz = 60
max_rollback_ticks = 8
mtu_bytes = 1180

[assets]
pack_output = "build/assets.flpk"
EOF

    cat > "${dest}/pixi.toml" <<EOF
[workspace]
name = "${app_name}"
version = "0.1.0"
description = "Pure-Mojo 1.2 standalone game powered by Flint Engine v5"
channels = ["https://conda.modular.com/max", "conda-forge"]
platforms = ["linux-64", "linux-aarch64"]

[dependencies]
mojo = ">=1.2.0,<1.3"

[tasks]
play = "bash tools/run.sh"
EOF

    cat > "${dest}/tools/run.sh" <<EOF
#!/usr/bin/env bash
set -euo pipefail
APP_ROOT="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")/.." && pwd)"
FLINT_ROOT="\${FLINT_ROOT:-${ROOT}}"
mkdir -p "\${APP_ROOT}/build"

MOJO_BIN="\${MOJO:-}"
if [[ -z "\$MOJO_BIN" ]]; then
    if [[ -x "\${APP_ROOT}/.pixi/envs/default/bin/mojo" ]]; then
        PFX="\${APP_ROOT}/.pixi/envs/default"
        export MOJO_PREFIX="\$PFX"
        export MODULAR_HOME="\${PFX}/share/max"
        export LD_LIBRARY_PATH="\${PFX}/lib\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
        MOJO_BIN="\${PFX}/bin/mojo"
