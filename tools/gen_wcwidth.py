#!/usr/bin/env python3
"""Generates src/flint/studio/wcwidth_tables.mojo (terminal cell widths for IdeGrid).

    pixi run python3 tools/gen_wcwidth.py           # rewrite the table module in place
    pixi run python3 tools/gen_wcwidth.py --check   # exit 1 when the checked-in tables are stale

Run it with the pixi environment's Python so the Unicode version is reproducible (a
different Python ships a different `unicodedata` and --check reports the mismatch).

Data comes from Python's `unicodedata` (its `unidata_version` is recorded in the output):
  zero width : General_Category Mn / Me / Cf (except U+00AD SOFT HYPHEN, which prints),
               Hangul Jungseong / Jongseong jamo (U+1160-U+11FF, U+D7B0-U+D7FF), and the
               emoji skin-tone modifiers U+1F3FB-U+1F3FF (they attach to the preceding emoji).
               Mn already covers the variation selectors and Cf covers ZWJ/ZWNJ and tags.
  wide       : East_Asian_Width W or F. Since Unicode 9 every Emoji_Presentation=Yes code
               point is EAW=W, so this also gives emoji presentation two cells. Unassigned
               code points in the CJK planes default to W as UAX #11 requires.
Zero width wins where both apply (e.g. U+302A-U+302D, U+3099-U+309A).
"""
import os
import sys
import unicodedata

OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "src", "flint", "studio", "wcwidth_tables.mojo"
)


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_zero(cp):
    if cp == 0x00AD:
        return False
    if 0x1160 <= cp <= 0x11FF or 0xD7B0 <= cp <= 0xD7FF or 0x1F3FB <= cp <= 0x1F3FF:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me", "Cf")


def is_wide(cp):
    if 0xD800 <= cp <= 0xDFFF or is_zero(cp):
        return False
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def table(name, rs):
    lines = [
        "comptime %s_N: Int = %d" % (name, len(rs)),
        "comptime %s: Array[Int32, %d] = [" % (name, 2 * len(rs)),
    ]
    flat = ["0x%X" % v for r in rs for v in r]
    for i in range(0, len(flat), 10):
        lines.append("    " + ", ".join(flat[i : i + 10]) + ",")
    lines.append("]")
    return "\n".join(lines)


def render():
    ver = unicodedata.unidata_version
    return (
        '"""Generated by tools/gen_wcwidth.py from Python unicodedata (Unicode %s); do not edit.\n'
        "\n"
        "Inclusive [lo, hi] code point ranges, sorted and disjoint, for binary search in\n"
        "`flint.studio.ide_grid.char_width`. `ZERO_WIDTH`: Mn/Me/Cf (not U+00AD), Hangul medial/final\n"
        "jamo and emoji skin-tone modifiers. `WIDE`: East Asian Wide/Fullwidth, which includes\n"
        "every Emoji_Presentation code point.\n"
        '"""\n'
        'comptime WCWIDTH_UNICODE_VERSION: StaticString = "%s"\n'
        "\n"
        "%s\n"
        "\n"
        "%s\n"
    ) % (ver, ver, table("ZERO_WIDTH", ranges(is_zero)), table("WIDE", ranges(is_wide)))


def main():
    text = render()
    if "--check" in sys.argv:
        with open(OUT) as f:
            current = f.read()
        if current != text:
            print("wcwidth tables are stale for Unicode %s (or were generated by another Python)"
                  % unicodedata.unidata_version, file=sys.stderr)
            sys.exit(1)
        sys.exit(0)
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote %s (Unicode %s)" % (os.path.normpath(OUT), unicodedata.unidata_version))


if __name__ == "__main__":
    main()
